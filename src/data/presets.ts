export function createDefaultSignPanel(overrides: Partial<SignPanelConfig> = {}): SignPanelConfig {
  return {
    id: overrides.id || `sign-${Math.random().toString(36).slice(2, 8)}`,
    name: overrides.name || 'Sign Panel',
    mountSlot: 'center',
    xOffset: 0,
    yOffset: 0,
    zOffset: 0,
    rotationZ: 0,
    scale: 1,
    shape: 'rounded-rect',
    width: 1.8,
    height: 1.2,
    cornerRadius: 0.1,
    thickness: 0.016,
    colorPreset: 'freeway-green',
    bgColor: '#006B54',
    borderColor: '#F4F6F8',
    textColor: '#F4F6F8',
    accentColor: '#C8102E',
    borderWidth: 0.035,
    borderInset: 0.025,
    sheetingType: 'diamond-cubed',
    showFaceBolts: true,
    wearAmount: 0.08,
    fontFamily: 'HighwayGothicExp',
    headerText: '',
    subHeaderText: '',
    lines: [
      { id: 'l1', text: 'FREEWAY', fontSize: 82, letterSpacing: 4, align: 'center' },
      { id: 'l2', text: 'ENTRANCE', fontSize: 82, letterSpacing: 4, align: 'center' },
    ],
    dividerLine: 'none',
    badges: [],
    badgeLayout: 'top-row',
    arrowType: 'none',
    arrowPosition: 'bottom',
    arrowScale: 1,
    pictogramType: 'none',
    pictogramPosition: 'center',
    pictogramScale: 1,
    exitTab: {
      enabled: false,
      text: 'EXIT 4',
      align: 'right',
      widthRatio: 0.42,
    },
    ...overrides,
  };
}

